"""Derive transparent crop/phase-conditioned Markov rows from local climate and FAO-56 Kc.

The transitions are generated by a daily bucket model, not observed field data.
Only annual crops with a consistent FAO-56 phase schedule and a MAPA ZARC
planting window are included. Off-season demand is explicitly the Kc=1
reference surface; this is not a measured fallow or cover-crop water balance.
"""

from __future__ import annotations

import csv
from hashlib import sha256
import json
import sys
from collections import Counter, defaultdict
from datetime import date
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
PROFILE_ROOT = ROOT / "data" / "profiles"
PARAMETERS_PATH = ROOT / "data" / "reference" / "crop-water-parameters.json"
MIN_DIRECT = 30
SPINUP_LAST_YEAR = 1982
ENVIRONMENTS = ("dry", "normal", "wet")
WATER_ORDER = ("baixa", "media", "alta")
WATER_IDS = {"baixa": "water_low", "media": "water_medium", "alta": "water_high"}


def read_json(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


def write_json(path: Path, payload) -> None:
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def parse_number(value: str) -> float | None:
    if value is None or value.strip() == "":
        return None
    try:
        return float(value)
    except ValueError:
        return None


def water_class(fraction: float) -> str:
    if fraction <= 1 / 3:
        return "baixa"
    if fraction <= 2 / 3:
        return "media"
    return "alta"


def period_start(day: date) -> date:
    return date(day.year, day.month, 1 if day.day <= 15 else 16)


def decendio_start(year: int, decendio: int) -> date:
    month = (decendio - 1) // 3 + 1
    within_month = (decendio - 1) % 3
    return date(year, month, (1, 11, 21)[within_month])


def annual_plant_date(day: date, decendio: int) -> date:
    planted_this_year = decendio_start(day.year, decendio)
    if day >= planted_this_year:
        return planted_this_year
    return decendio_start(day.year - 1, decendio)


def crop_phase(day: date, planting_decendio: int, crop: dict) -> tuple[str, float]:
    planting = annual_plant_date(day, planting_decendio)
    elapsed = (day - planting).days
    duration = int(crop["duration_days"])
    kc = crop["kc"]
    stages = crop["stage_days"]
    if elapsed >= duration:
        return "off_crop_reference", 1.0
    initial = int(stages["initial"])
    development = int(stages["development"])
    mid = int(stages["mid"])
    late = int(stages["late"])
    if elapsed < initial:
        return "initial", float(kc["initial"])
    if elapsed < initial + development:
        fraction = (elapsed - initial) / max(development, 1)
        value = float(kc["initial"]) + fraction * (float(kc["mid"]) - float(kc["initial"]))
        return "development", value
    if elapsed < initial + development + mid:
        return "mid", float(kc["mid"])
    fraction = (elapsed - initial - development - mid) / max(late, 1)
    value = float(kc["mid"]) + fraction * (float(kc["end"]) - float(kc["mid"]))
    return "late", value


def state_id(water: str, phase: str) -> str:
    return f"{WATER_IDS[water]}__{phase}"


def load_daily(profile_dir: Path) -> list[dict]:
    rows = []
    with (profile_dir / "climate-daily.csv").open(encoding="utf-8-sig", newline="") as stream:
        for item in csv.DictReader(stream):
            day = date.fromisoformat(item["date_local"])
            if day.year > 2025 or day.year < 1981:
                continue
            if item["quality_valid"].casefold() != "true":
                continue
            rain, eto = parse_number(item["precipitation_mm"]), parse_number(item["eto_mm_day"])
            if rain is None or eto is None:
                continue
            rows.append({"date": day, "rain": rain, "eto": eto})
    if not rows or rows[0]["date"] != date(1981, 1, 1) or rows[-1]["date"] != date(2025, 12, 31):
        raise ValueError(f"{profile_dir.name}: climate must cover complete 1981–2025 daily years")
    return rows


def period_environment(history: dict[str, list[str]]) -> dict[date, str]:
    result = {}
    for year_string, labels in history.items():
        year = int(year_string)
        if year > 2025:
            continue
        if len(labels) != 24:
            raise ValueError(f"Expected 24 environmental labels for {year}")
        for month in range(1, 13):
            result[date(year, month, 1)] = labels[(month - 1) * 2]
            result[date(year, month, 16)] = labels[(month - 1) * 2 + 1]
    return result


def supported_parameters() -> dict[str, dict]:
    payload = read_json(PARAMETERS_PATH)
    result = {}
    for crop in payload["crops"]:
        stages = crop.get("stage_days")
        duration = crop.get("duration_days")
        if not stages or not duration or not crop.get("kc"):
            continue
        if sum(int(value) for value in stages.values()) != int(duration):
            continue
        if duration >= 365:
            continue
        result[crop["id"]] = crop
    return result


def derive_scenario(profile_dir: Path, rows: list[dict], environments: dict[date, str], awc: float, crop: dict, planting_decendio: int, official_labels: list[str]) -> dict:
    period_rows = []
    storage = awc * 0.5
    current_period = None
    start_storage = storage
    for weather in rows:
        day = weather["date"]
        key = period_start(day)
        if current_period is None:
            current_period = key
            start_storage = storage
        elif key != current_period:
            period_rows.append({"start": current_period, "start_storage": start_storage, "end_storage": storage})
            current_period = key
            start_storage = storage
        _, kc = crop_phase(day, planting_decendio, crop)
        storage = min(awc, storage + weather["rain"])
        storage = max(0.0, storage - min(storage, weather["eto"] * kc))
    if current_period is not None:
        period_rows.append({"start": current_period, "start_storage": start_storage, "end_storage": storage})

    direct: dict[tuple[str, str], Counter] = defaultdict(Counter)
    context_n: Counter = Counter()
    states = {}
    for index, current in enumerate(period_rows[:-1]):
        next_period = period_rows[index + 1]
        start = current["start"]
        if start.year <= SPINUP_LAST_YEAR:
            continue
        env = environments[start]
        current_phase, _ = crop_phase(start, planting_decendio, crop)
        next_phase, _ = crop_phase(next_period["start"], planting_decendio, crop)
        water_before = water_class(current["start_storage"] / awc)
        water_after = water_class(current["end_storage"] / awc)
        source = state_id(water_before, current_phase)
        destination = state_id(water_after, next_phase)
        states[source] = {"id": source, "water": water_before, "phase": current_phase, "crop": crop["id"]}
        states[destination] = {"id": destination, "water": water_after, "phase": next_phase, "crop": crop["id"]}
        direct[(source, env)][destination] += 1
        context_n[(source, env)] += 1

    action = f"crop:{crop['id']}:planting_decendio:{planting_decendio}"
    transitions = []
    for source in sorted({key[0] for key in direct}):
        pooled = Counter()
        for env in ENVIRONMENTS:
            pooled.update(direct[(source, env)])
        if not pooled:
            continue
        for env in ENVIRONMENTS:
            counts = direct[(source, env)]
            n = context_n[(source, env)]
            support = "derived" if n >= MIN_DIRECT else "pooled"
            chosen = counts if support == "derived" else pooled
            transitions.append({
                "state": source,
                "action": action,
                "environment": env,
                "counts": dict(sorted(chosen.items())),
                "support": support,
                "sample_size": int(n),
                "effective_sample_size": int(sum(chosen.values())),
                "pooling": None if support == "derived" else "same water×phase state pooled across dry/normal/wet contexts",
                "provenance": "scenario_level",
            })

    initial_phase, _ = crop_phase(date(2026, 1, 1), planting_decendio, crop)
    initial_id = state_id("media", initial_phase)
    states.setdefault(initial_id, {"id": initial_id, "water": "media", "phase": initial_phase, "crop": crop["id"]})
    if not transitions:
        raise ValueError(f"No Markov transition rows for {crop['id']} at ZARC decendio {planting_decendio}")
    return {
        "crop_parameter_id": crop["id"],
        "crop_name_pt": crop["name_pt"],
        "official_zarc_crop_labels": sorted(set(official_labels)),
        "planting_decendio": planting_decendio,
        "action": action,
        "initial_state_id": initial_id,
        "initial_storage_fraction": 0.5,
        "periods_per_year": 24,
        "training_period": ["1981-01-01", "2025-12-31"],
        "history_id": "profile.environment.json",
        "phase_ids": ["initial", "development", "mid", "late", "off_crop_reference"],
        "parameter_reference": crop,
        "off_crop_demand": {"kc": 1.0, "status": "reference ET0 demand; no cover/fallow crop observed"},
        "states": [states[key] for key in sorted(states)],
        "transitions": transitions,
        "support": "derived_process_model",
        "provenance": "Derived daily bucket using NASA POWER precipitation and ET0, SoilGrids/Saxton–Rawls AWC, and a FAO-56 crop Kc phase curve. This is not a field transition, crop-yield response, or observed management effect.",
        "limitations": [
            "The water bucket is municipal-centroid SoilGrids AWC, not a field root-zone measurement.",
            "FAO-56 stage durations and Kc are literature references, not cultivar-specific Brazilian calibration.",
            "Outside the crop cycle the bucket uses the Kc=1 reference demand; it does not represent measured bare soil or an unmeasured cover crop.",
            "Water transitions do not predict yield, revenue, soil-health change, or economic return.",
        ],
    }


def main() -> None:
    only = sys.argv[sys.argv.index("--profiles") + 1:] if "--profiles" in sys.argv else None
    coverage_path = ROOT / "data" / "reference" / "crop-markov-coverage.json"
    parameters = supported_parameters()
    # With --profiles only those are derived; the coverage of the others is kept as it was.
    report = {"profiles": dict(read_json(coverage_path).get("profiles", {})) if only else {}}
    for profile_dir in sorted(path for path in PROFILE_ROOT.iterdir() if path.is_dir() and (path / "manifest.json").exists()):
        if only and profile_dir.name not in only:
            continue
        zarc = read_json(profile_dir / "zarc-planting-windows.json")
        soil = read_json(profile_dir / "soil-profile.json")
        history = read_json(profile_dir / "environment.json")
        env_by_period = period_environment(history)
        weather = load_daily(profile_dir)
        valid = {}
        rejected = {}
        for row in zarc["rows"]:
            crop_id = row.get("crop_parameter_id")
            crop = parameters.get(crop_id)
            if crop is None:
                rejected[row["crop"]] = "no consistent annual FAO-56 phase-duration curve, or ZARC crop is a mixture"
                continue
            for risk, decendios in row["planting_decendios_by_risk_percent"].items():
                for decendio in decendios:
                    key = (crop_id, int(decendio))
                    valid.setdefault(key, set()).add(row["crop"])
        scenarios = []
        for (crop_id, decendio), official_labels in sorted(valid.items()):
            scenarios.append(derive_scenario(
                profile_dir, weather, env_by_period,
                float(soil["available_water_capacity_mm"]),
                parameters[crop_id], decendio, sorted(official_labels),
            ))
        payload = {
            "schema_version": "1.0.0",
            "purpose": "Crop- and ZARC-window-conditioned derived water transitions for transparent Monte Carlo scenarios.",
            "index": ["state (water×phase)", "action (crop×planting decendio)", "environment (seasonally aligned rainfall class)"],
            "source": {
                "climate": "NASA POWER daily normalized profile; ET0 computed using FAO-56 Penman–Monteith with documented Hargreaves fallback",
                "soil": "SoilGrids mean prediction; AWC derived using Saxton–Rawls, 0–100 cm",
                "crop_water": "FAO-56 Table 11–12 Kc and stage-day references",
                "planting_eligibility": "MAPA SISZARC public report rows for the profile municipality; model scenarios emitted only for a nonzero 20/30/40 risk decendio in at least one selected group/soil row",
                "pseudocount": "0.5 per observed viable next-state destination at Monte Carlo load time; not part of the historical counts",
            },
            "scenario_count": len(scenarios),
            "scenarios": scenarios,
            "not_simulated_zarc_crops": rejected,
        }
        output = profile_dir / "crop-markov-scenarios.json"
        write_json(output, payload)
        manifest_path = profile_dir / "manifest.json"
        manifest = read_json(manifest_path)
        manifest.setdefault("datasets", {})["crop-markov-scenarios.json"] = {
            "origem": "NASA POWER + SoilGrids/Saxton–Rawls + FAO-56 + janelas MAPA ZARC",
            "responsavel": "Field Shift derivação; sem transição de campo observada",
            "frequencia": "quinzenal, indexada por água×fase×ambiente e ação×decêndio ZARC",
            "unidade": "contagens por destino de água×fase; CAD em mm; Kc adimensional",
            "periodo": "1983–2025; spin-up 1981–1982",
            "resolucao": "perfil municipal × cultura com Kc validado × decêndio de plantio elegível no ZARC",
            "qualidade": "balanço derivado; off-season usa Kc=1 de referência; Kc FAO-56 não calibrado regionalmente; não prevê produtividade ou VPL",
            "sha256": sha256(output.read_bytes()).hexdigest(),
        }
        reference_path = ROOT / "data" / "reference" / "crop-water-parameters.json"
        manifest["datasets"]["crop-water-parameters.json"] = {
            "origem": "FAO-56 Irrigation and Drainage Paper 56, Tabelas 11–12",
            "responsavel": "FAO; extração de referência Field Shift",
            "frequencia": "por cultura e fase",
            "unidade": "Kc adimensional; duração em dias",
            "periodo": "parâmetros tabulados sem ajuste climático local",
            "resolucao": "espécie/grupo de cultivo; nem todo sistema tem curva anual compatível",
            "qualidade": "referência bibliográfica; cada proxy e inconsistência estão registrados no arquivo",
            "sha256": sha256(reference_path.read_bytes()).hexdigest(),
        }
        assumptions_path = profile_dir / "assumptions.json"
        assumptions = read_json(assumptions_path)
        assumptions["crop_markov_scenario"] = {
            "transition_index": "state water×FAO phase × MAPA risk-context environment × selected crop/planting-decad",
            "crop_water": "Kc follows FAO-56 phase curve during the crop cycle; off-season uses Kc=1 reference demand",
            "eligibility": "only decendios with MAPA ZARC risk 20/30/40% for at least one municipality cultivar-group and soil-class row are emitted",
            "monte_carlo": "shared seasonal environment blocks and per-trajectory Dirichlet row draws; 0.5 pseudocount only on historically viable next states",
            "interpretation": "process-model sensitivity scenario; not observed effect, yield forecast, crop recommendation, or economic ranking",
        }
        write_json(assumptions_path, assumptions)
        manifest["datasets"]["assumptions.json"]["sha256"] = sha256(assumptions_path.read_bytes()).hexdigest()
        write_json(manifest_path, manifest)
        print(f"{profile_dir.name}: {len(scenarios)} crop-by-planting-window Markov scenarios; {len(rejected)} ZARC crop labels withheld")
        report["profiles"][profile_dir.name] = {
            "file": output.relative_to(ROOT).as_posix(),
            "scenario_count": len(scenarios),
            "scenarios": [{"crop_parameter_id": row["crop_parameter_id"], "planting_decendio": row["planting_decendio"], "transition_rows": len(row["transitions"])} for row in scenarios],
            "not_simulated_zarc_crops": rejected,
        }
    write_json(ROOT / "data" / "reference" / "crop-markov-coverage.json", report)


if __name__ == "__main__":
    main()
